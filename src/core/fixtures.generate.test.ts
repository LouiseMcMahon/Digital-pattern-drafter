import { writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { fitBody } from './fit';
import { FIXTURE_SEEDS } from './fixtureSeeds';
import { loadBodyFromDisk } from './loadBodyNode';
import { MEASUREMENT_NAMES, Measurer } from './measure';

/**
 * Regenerates src/core/fixtures.ts from the seed measurements: `npm run fixtures:regenerate`.
 * Skipped unless REGEN_FIXTURES is set. Follow with `npm run golden:refit`, and see ENGINEERING.md
 * ("Changing the model") for what to commit and how.
 */
describe.skipIf(!process.env.REGEN_FIXTURES)('regenerate fixtures', () => {
  it('fits each seed set and writes fixtures.ts', async () => {
    const body = await loadBodyFromDisk();
    const measurer = new Measurer(body);
    let out = `import type { FitTargets } from './fit';

/**
 * GENERATED by \`npm run fixtures:regenerate\` (src/core/fixtures.generate.test.ts) from fixtureSeeds.ts. Do not edit by hand.
 *
 * Reference measurement sets (cm) for acceptance tests (REQUIREMENTS.md R1/R2). The first users are
 * 6'2" (188 cm) women, so tall bodies in several builds are first-class fixtures.
 *
 * Each set is generated from a fitted body (fit the 20 round seed numbers, read all measurements off the
 * result, round to 0.5 cm like a tape) so the set is self-consistent: armLength = upperArmLength +
 * forearmLength, crotchDepth = waistHeight - insideLeg, and so on. Inventing 34 numbers by hand produced
 * contradictory sets. These are NOT real people; replace with real sets when available.
 *
 * Measured in the standard tailor pose (REQUIREMENTS.md R5). Changing the pose, the baked body or a
 * measurement definition changes what a body reads, so regenerate these together with the golden files
 * (ENGINEERING.md, "Changing the model").
 */
export const FIXTURES: Record<string, { label: string; preset: 'female' | 'male'; targets: FitTargets }> = {
`;
    for (const [key, fx] of Object.entries(FIXTURE_SEEDS)) {
      const r = fitBody(body, measurer, fx.seed, { preset: fx.preset });
      if (r.unmet.length) throw new Error(`${key}: seed measurements could not be matched: ${JSON.stringify(r.unmet)}`);
      const all = measurer.measure(r.shape);
      const tape = (v: number) => Math.round(v * 2) / 2; // a tape reads to 0.5 cm
      const rounded: Record<string, number> = Object.fromEntries(MEASUREMENT_NAMES.map((n) => [n, tape(all[n])]));
      // Measurements tied together by definition are derived from their rounded parts, never rounded
      // independently, so the identities hold exactly (independent rounding can break them by 0.75 cm).
      rounded.armLength = rounded.upperArmLength + rounded.forearmLength;
      rounded.crotchDepth = rounded.waistHeight - rounded.insideLeg;
      const vals = MEASUREMENT_NAMES.map((n) => `${n}: ${rounded[n]}`).join(', ');
      out += `  ${key}: {\n    label: ${JSON.stringify(fx.label)},\n    preset: '${fx.preset}',\n    targets: { ${vals} },\n  },\n`;
    }
    out += '};\n';
    writeFileSync('src/core/fixtures.ts', out);
  }, 900_000);
});
